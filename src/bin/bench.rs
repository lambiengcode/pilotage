/// `n` sources each returning a JSON document padded to roughly `bytes`.
fn wide_routes(n: usize, bytes: usize) -> Routes {
    let mut routes = Routes::new();
    for i in 0..n {
        let padding = "x".repeat(bytes.saturating_sub(120));
        routes.insert(
            format!("/s{i}"),
            (
                200,
                serde_json::json!({
                    "value": (i * 17) as i64,
                    "name": format!("source {i}"),
                    "series": [1, 2, 3, 4, 5],
                    "padding": padding
                })
                .to_string(),
            ),
        );
    }
    routes
}

fn wide_pack(server: &MockServer, n: usize) -> String {
    let mut s = String::from("name = \"bench\"\ndetect = [\"bench:{name}\"]\n");
    for i in 0..n {
        s.push_str(&format!(
            "\n[[source]]\nid = \"s{i}\"\nkind = \"api\"\nurl = \"{}\"\nttl = \"1h\"\n[source.map]\nv{i} = \".value\"\nn{i} = \".name\"\n",
            server.url(&format!("/s{i}"))
        ));
    }
    for i in 0..n {
        s.push_str(&format!(
            "\n[[metric]]\nid = \"m{i}\"\nfact = \"v{i}\"\nwarn = \"< 10\"\nfail = \"< 0\"\nweight = 1.0\n"
        ));
    }
    s
}

struct BenchEnv {
    home: PathBuf,
}

impl BenchEnv {
    fn new(tag: &str) -> BenchEnv {
        let home = std::env::temp_dir().join(format!(
            "pilotage-bench-{tag}-{}-{}",
            std::process::id(),
            Instant::now().elapsed().as_nanos() as u64
                ^ std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .unwrap()
                    .as_nanos() as u64
        ));
        std::fs::create_dir_all(home.join("packs")).unwrap();
        BenchEnv { home }
    }

    fn write_pack(&self, toml: &str) {
        std::fs::write(self.home.join("packs").join("bench.toml"), toml).unwrap();
    }

    fn run(&self, bin: &Path, args: &[&str], extra: &[(&str, &str)]) -> std::process::Output {
        let mut cmd = Command::new(bin);
        cmd.args(args)
            .env("PILOTAGE_HOME", &self.home)
            // Politeness delay off: this measures pilotage's concurrency, not its
            // rate limiter, and every configuration here is measured the same way.
            .env("PILOTAGE_HOST_INTERVAL_MS", "0");
        for (k, v) in extra {
            cmd.env(k, v);
        }
        cmd.output().expect("running pilotage")
    }
}

impl Drop for BenchEnv {
    fn drop(&mut self) {
        std::fs::remove_dir_all(&self.home).ok();
    }
}

fn time<F: FnOnce()>(f: F) -> f64 {
    let t = Instant::now();
    f();
    t.elapsed().as_secs_f64() * 1000.0
}

fn median(v: &mut [f64]) -> f64 {
    v.sort_by(f64::total_cmp);
    v[v.len() / 2]
}

