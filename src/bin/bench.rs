//! Benchmark harness.
//!
//! Everything here measures something real against a local server with configurable
//! latency. Nothing is modelled or extrapolated, and the two numbers pilotage cannot
//! honestly measure without provider accounts — model cost and end-to-end agent token
//! spend — are deliberately absent rather than estimated.
//!
//! Run with `cargo run --release --bin bench`. Writes `docs/bench.md` and the SVG
//! plots the README embeds.

use pilotage::testserver::{MockServer, Routes};
use pilotage::toon::{Toon, approx_tokens};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant};

/// Latency injected into every mock response. Loopback is sub-millisecond, and a
/// fan-out measurement taken there would flatter concurrency by removing the very
/// thing concurrency hides.
const SERVER_LATENCY: Duration = Duration::from_millis(25);
const REPS: usize = 7;

fn main() {
    let bin = binary_path();
    if !bin.exists() {
        eprintln!(
            "error: {} not found — run `cargo build --release` first",
            bin.display()
        );
        std::process::exit(1);
    }
    let docs = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("docs");
    std::fs::create_dir_all(&docs).expect("creating docs/");

    println!("pilotage benchmarks");
    println!("binary: {}", bin.display());
    println!(
        "server latency: {}ms, {REPS} reps, reporting medians\n",
        SERVER_LATENCY.as_millis()
    );

    let mut md = String::new();
    md.push_str("# Benchmarks\n\n");
    md.push_str(&format!(
        "Generated by `cargo run --release --bin bench`. Medians of {REPS} runs against a local \
         server with {}ms injected latency, on {} / {}.\n\n",
        SERVER_LATENCY.as_millis(),
        std::env::consts::OS,
        std::env::consts::ARCH
    ));

    let payload = bench_payload(&mut md, &docs);
    bench_context(&bin, &mut md, &docs);
    bench_cache(&bin, &mut md, &docs);
    bench_fanout(&bin, &mut md, &docs);
    bench_startup(&bin, &mut md);

    md.push_str("\n## What is not measured here\n\n");
    md.push_str(
        "* **Model cost.** Rung 3 only runs with a provider key configured. Pilotage \
         accounts for it from the provider's reported token usage at run time; there is \
         no fixed number to publish, and inventing one would be worse than leaving it out.\n",
    );
    md.push_str(
        "* **End-to-end agent token spend.** That depends on the calling model and the \
         task. The payload measurements above are the part pilotage controls.\n",
    );

    std::fs::write(docs.join("bench.md"), &md).expect("writing docs/bench.md");
    println!("\nwrote {}", docs.join("bench.md").display());
    println!("median TOON saving vs JSON: {:.0}%", payload);
}

fn binary_path() -> PathBuf {
    // The bench binary sits beside the pilotage binary in the same profile directory.
    std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.join("pilotage")))
        .unwrap_or_else(|| PathBuf::from("target/release/pilotage"))
}

// ---------------------------------------------------------------------------
// 1. Payload size: TOON vs JSON
// ---------------------------------------------------------------------------

fn bench_payload(md: &mut String, docs: &Path) -> f64 {
    let counts = [1usize, 5, 10, 25, 50, 100];
    let mut toon_bytes = Vec::new();
    let mut json_bytes = Vec::new();
    let mut savings = Vec::new();

    for &n in &counts {
        let rows: Vec<Vec<String>> = (0..n)
            .map(|i| {
                vec![
                    format!("metric_{i}"),
                    format!("{}", i * 37),
                    ["ok", "warn", "fail"][i % 3].to_string(),
                    format!("{}", 1 + i % 3),
                ]
            })
            .collect();

        let mut t = Toon::new();
        t.table("signals", &["metric", "value", "status", "w"], &rows);
        let toon = t.render();

        let json = serde_json::to_string(
            &rows
                .iter()
                .map(|r| {
                    serde_json::json!({
                        "metric": r[0], "value": r[1], "status": r[2], "w": r[3]
                    })
                })
                .collect::<Vec<_>>(),
        )
        .unwrap();

        toon_bytes.push(toon.len() as f64);
        json_bytes.push(json.len() as f64);
        savings.push((1.0 - toon.len() as f64 / json.len() as f64) * 100.0);
    }

    md.push_str("## 1. Payload size — TOON vs JSON\n\n");
    md.push_str(
        "The same signal table serialised both ways. TOON hoists the record keys into a \
         single header row, so the saving grows with the number of records and is \
         negative for a single one — which is why pilotage uses scalars, not tables, \
         for singletons.\n\n",
    );
    md.push_str("| records | TOON bytes | JSON bytes | saving | TOON tokens* | JSON tokens* |\n");
    md.push_str("|--:|--:|--:|--:|--:|--:|\n");
    for (i, &n) in counts.iter().enumerate() {
        md.push_str(&format!(
            "| {n} | {} | {} | {:.0}% | {} | {} |\n",
            toon_bytes[i] as usize,
            json_bytes[i] as usize,
            savings[i],
            approx_tokens(&"x".repeat(toon_bytes[i] as usize)),
            approx_tokens(&"x".repeat(json_bytes[i] as usize)),
        ));
    }
    md.push_str("\n\\* approximate, at 4 characters per token.\n\n");
    md.push_str("![TOON vs JSON payload size](bench-payload.svg)\n\n");

    println!("1. payload size");
    for (i, &n) in counts.iter().enumerate() {
        println!(
            "   {n:>4} records: toon {:>6}B  json {:>6}B  saving {:>5.1}%",
            toon_bytes[i] as usize, json_bytes[i] as usize, savings[i]
        );
    }

    std::fs::write(
        docs.join("bench-payload.svg"),
        bar_chart(
            "Payload size: TOON vs JSON",
            "bytes",
            &counts.iter().map(|c| format!("{c}")).collect::<Vec<_>>(),
            "records",
            &[
                Series {
                    name: "JSON".into(),
                    color: "#f59e0b",
                    values: json_bytes,
                },
                Series {
                    name: "TOON".into(),
                    color: "#4f7cff",
                    values: toon_bytes,
                },
            ],
            false,
        ),
    )
    .unwrap();

    // The single-record case is a known loss; report the median of the rest.
    let mut multi: Vec<f64> = savings[1..].to_vec();
    multi.sort_by(f64::total_cmp);
    multi[multi.len() / 2]
}

// ---------------------------------------------------------------------------
// 2. Context economics: bytes read vs bytes returned
// ---------------------------------------------------------------------------

fn bench_context(bin: &Path, md: &mut String, docs: &Path) {
    let server = MockServer::with_latency(wide_routes(12, 40_000), Duration::from_millis(5));
    let env = BenchEnv::new("context");
    env.write_pack(&wide_pack(&server, 12));

    let out = env.run(bin, &["research", "bench:x"], &[]);
    let brief = String::from_utf8_lossy(&out.stdout).len() as f64;

    let out_full = env.run(bin, &["research", "bench:x", "--full"], &[]);
    let full = String::from_utf8_lossy(&out_full.stdout).len() as f64;

    // What the sources actually returned — what would land in an agent's context if
    // it fetched these pages itself.
    let json = env.run(bin, &["report", "--json"], &[]);
    let run: serde_json::Value = serde_json::from_slice(&json.stdout).expect("run JSON");
    let read: f64 = run["sources"]
        .as_array()
        .unwrap()
        .iter()
        .map(|s| s["bytes"].as_f64().unwrap_or(0.0))
        .sum();

    let ratio = read / brief;

    md.push_str("## 2. Context economics\n\n");
    md.push_str(
        "One run over 12 sources returning 40 KB each. `bytes read` is what the sources \
         actually returned — what would land in an agent's context window if it fetched \
         them itself. `bytes returned` is what pilotage hands back.\n\n",
    );
    md.push_str("| | bytes | tokens* |\n|:--|--:|--:|\n");
    md.push_str(&format!(
        "| read from sources | {} | {} |\n",
        read as usize,
        approx_tokens(&"x".repeat(read as usize))
    ));
    md.push_str(&format!(
        "| returned, default view | {} | {} |\n",
        brief as usize,
        approx_tokens(&"x".repeat(brief as usize))
    ));
    md.push_str(&format!(
        "| returned, `--full` | {} | {} |\n",
        full as usize,
        approx_tokens(&"x".repeat(full as usize))
    ));
    md.push_str(&format!(
        "\n**{ratio:.0}× reduction** on the default view.\n\n"
    ));
    md.push_str("![Bytes read vs returned](bench-context.svg)\n\n");

    println!("\n2. context economics");
    println!(
        "   read {:>8.0}B  returned {:>6.0}B  full {:>6.0}B  ratio {ratio:.0}x",
        read, brief, full
    );

    std::fs::write(
        docs.join("bench-context.svg"),
        bar_chart(
            "Bytes read vs bytes returned to the agent",
            "bytes (log scale)",
            &[
                "read from sources".into(),
                "returned (--full)".into(),
                "returned (default)".into(),
            ],
            "",
            &[Series {
                name: "bytes".into(),
                color: "#4f7cff",
                values: vec![read, full, brief],
            }],
            true,
        ),
    )
    .unwrap();
}

// ---------------------------------------------------------------------------
// 3. Cache: cold vs warm
// ---------------------------------------------------------------------------

fn bench_cache(bin: &Path, md: &mut String, docs: &Path) {
    let server = MockServer::with_latency(wide_routes(8, 4_000), SERVER_LATENCY);
    let mut cold = Vec::new();
    let mut warm = Vec::new();

    for _ in 0..REPS {
        // A fresh home each rep, so "cold" really is cold.
        let env = BenchEnv::new("cold");
        env.write_pack(&wide_pack(&server, 8));
        cold.push(time(|| {
            env.run(bin, &["research", "bench:x"], &[]);
        }));
        warm.push(time(|| {
            env.run(bin, &["research", "bench:x"], &[]);
        }));
    }

    let (c, w) = (median(&mut cold), median(&mut warm));

    md.push_str("## 3. Cache — cold vs warm\n\n");
    md.push_str(&format!(
        "Eight sources at {}ms each, end to end including process startup.\n\n",
        SERVER_LATENCY.as_millis()
    ));
    md.push_str("| | ms |\n|:--|--:|\n");
    md.push_str(&format!("| cold (all sources fetched) | {c:.1} |\n"));
    md.push_str(&format!("| warm (served from cache) | {w:.1} |\n"));
    md.push_str(&format!("\n**{:.0}× faster** warm.\n\n", c / w.max(0.001)));
    md.push_str("![Cold vs warm cache](bench-cache.svg)\n\n");

    println!("\n3. cache");
    println!(
        "   cold {c:>7.1}ms   warm {w:>7.1}ms   speedup {:.0}x",
        c / w.max(0.001)
    );

    std::fs::write(
        docs.join("bench-cache.svg"),
        bar_chart(
            "End-to-end run latency",
            "milliseconds",
            &["cold".into(), "warm".into()],
            "",
            &[Series {
                name: "ms".into(),
                color: "#10b981",
                values: vec![c, w],
            }],
            false,
        ),
    )
    .unwrap();
}

// ---------------------------------------------------------------------------
// 4. Fan-out: serial vs concurrent
// ---------------------------------------------------------------------------

fn bench_fanout(bin: &Path, md: &mut String, docs: &Path) {
    let counts = [1usize, 4, 8, 16, 32];
    let mut serial = Vec::new();
    let mut concurrent = Vec::new();

    for &n in &counts {
        let server = MockServer::with_latency(wide_routes(n, 2_000), SERVER_LATENCY);
        let pack = wide_pack(&server, n);

        let mut s = Vec::new();
        let mut c = Vec::new();
        for _ in 0..REPS {
            let e1 = BenchEnv::new("serial");
            e1.write_pack(&pack);
            s.push(time(|| {
                e1.run(
                    bin,
                    &["research", "bench:x"],
                    &[("PILOTAGE_CONCURRENCY", "1")],
                );
            }));

            let e2 = BenchEnv::new("conc");
            e2.write_pack(&pack);
            c.push(time(|| {
                e2.run(bin, &["research", "bench:x"], &[]);
            }));
        }
        serial.push(median(&mut s));
        concurrent.push(median(&mut c));
    }

    md.push_str("## 4. Fan-out — serial vs concurrent\n\n");
    md.push_str(&format!(
        "The same run with `PILOTAGE_CONCURRENCY=1` and at the default of 16, against \
         sources that take {}ms each. Serial cost grows with source count; concurrent \
         cost is roughly one round trip until the pool saturates.\n\n",
        SERVER_LATENCY.as_millis()
    ));
    md.push_str("| sources | serial ms | concurrent ms | speedup |\n|--:|--:|--:|--:|\n");
    for (i, &n) in counts.iter().enumerate() {
        md.push_str(&format!(
            "| {n} | {:.1} | {:.1} | {:.1}× |\n",
            serial[i],
            concurrent[i],
            serial[i] / concurrent[i].max(0.001)
        ));
    }
    md.push_str("\n![Serial vs concurrent fan-out](bench-fanout.svg)\n\n");

    println!("\n4. fan-out");
    for (i, &n) in counts.iter().enumerate() {
        println!(
            "   {n:>3} sources: serial {:>7.1}ms  concurrent {:>7.1}ms  {:.1}x",
            serial[i],
            concurrent[i],
            serial[i] / concurrent[i].max(0.001)
        );
    }

    std::fs::write(
        docs.join("bench-fanout.svg"),
        bar_chart(
            "Run latency by source count",
            "milliseconds",
            &counts.iter().map(|c| format!("{c}")).collect::<Vec<_>>(),
            "sources",
            &[
                Series {
                    name: "serial".into(),
                    color: "#f59e0b",
                    values: serial,
                },
                Series {
                    name: "concurrent".into(),
                    color: "#4f7cff",
                    values: concurrent,
                },
            ],
            false,
        ),
    )
    .unwrap();
}

// ---------------------------------------------------------------------------
// 5. Startup
// ---------------------------------------------------------------------------

fn bench_startup(bin: &Path, md: &mut String) {
    let env = BenchEnv::new("startup");
    let mut times = Vec::new();
    for _ in 0..(REPS * 3) {
        times.push(time(|| {
            env.run(bin, &["--version"], &[]);
        }));
    }
    let m = median(&mut times);

    md.push_str("## 5. Process startup\n\n");
    md.push_str(&format!(
        "`pilotage --version`, {} reps: **{m:.1}ms** median. This is the floor under \
         every invocation, and it is why the binary is Rust rather than a Node CLI \
         behind `npx`.\n\n",
        REPS * 3
    ));

    println!("\n5. startup");
    println!("   {m:.1}ms median over {} runs", REPS * 3);
}

