struct Series {
    name: String,
    color: &'static str,
    values: Vec<f64>,
}

/// A grouped bar chart with no external dependencies, themed for both light and dark
/// READMEs. An SVG loaded as an image evaluates its own media queries, so one file
/// works in either.
fn bar_chart(
    title: &str,
    y_label: &str,
    categories: &[String],
    x_label: &str,
    series: &[Series],
    log: bool,
) -> String {
    const W: f64 = 760.0;
    const H: f64 = 380.0;
    let (ml, mr, mt, mb) = (74.0, 24.0, 62.0, 54.0);
    let plot_w = W - ml - mr;
    let plot_h = H - mt - mb;

    let max = series
        .iter()
        .flat_map(|s| s.values.iter())
        .fold(0.0f64, |a, b| a.max(*b))
        .max(1.0);

    // Log plots span whole decades: the ticks then land on 100 / 1k / 10k rather than
    // on arbitrary values, and the top decade leaves headroom for the value labels.
    let min_pos = series
        .iter()
        .flat_map(|s| s.values.iter())
        .filter(|v| **v > 0.0)
        .fold(f64::MAX, |a, b| a.min(*b));
    let (lo, hi) = if log {
        (min_pos.max(1.0).log10().floor(), max.log10().ceil())
    } else {
        (0.0, max * 1.16)
    };
    let ticks = if log { (hi - lo).max(1.0) as usize } else { 4 };

    let scale = |v: f64| -> f64 {
        let t = if log {
            ((v.max(1.0).log10()) - lo) / (hi - lo)
        } else {
            (v - lo) / (hi - lo)
        };
        mt + plot_h - t.clamp(0.0, 1.0) * plot_h
    };

    let mut svg = String::new();
    svg.push_str(&format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="{}">
<style>
.title{{font:600 16px ui-sans-serif,-apple-system,'Segoe UI',Roboto,sans-serif;fill:#16181d}}
.axis{{font:11px ui-sans-serif,-apple-system,'Segoe UI',Roboto,sans-serif;fill:#6b7280}}
.val{{font:600 10px ui-sans-serif,-apple-system,'Segoe UI',Roboto,sans-serif;fill:#6b7280}}
.leg{{font:11px ui-sans-serif,-apple-system,'Segoe UI',Roboto,sans-serif;fill:#16181d}}
.grid{{stroke:#e5e7eb;stroke-width:1}}
@media (prefers-color-scheme: dark){{
.title{{fill:#e8eaed}} .axis{{fill:#9aa3b2}} .val{{fill:#9aa3b2}}
.leg{{fill:#e8eaed}} .grid{{stroke:#2a2f3a}}
}}
</style>
<text class="title" x="{ml}" y="26">{}</text>
"#,
        esc(title),
        esc(title)
    ));

    // Gridlines
    for i in 0..=ticks {
        let frac = i as f64 / ticks as f64;
        let y = mt + plot_h - frac * plot_h;
        let value = if log {
            10f64.powf(lo + frac * (hi - lo))
        } else {
            lo + frac * (hi - lo)
        };
        svg.push_str(&format!(
            r#"<line class="grid" x1="{ml}" y1="{y:.1}" x2="{:.1}" y2="{y:.1}"/>
<text class="axis" x="{:.1}" y="{:.1}" text-anchor="end">{}</text>
"#,
            ml + plot_w,
            ml - 9.0,
            y + 3.5,
            si(value)
        ));
    }

    // Legend (only when there is more than one series to distinguish)
    if series.len() > 1 {
        let mut x = ml;
        for s in series {
            svg.push_str(&format!(
                r#"<rect x="{x:.1}" y="38" width="10" height="10" rx="2" fill="{}"/>
<text class="leg" x="{:.1}" y="47">{}</text>
"#,
                s.color,
                x + 15.0,
                esc(&s.name)
            ));
            x += 22.0 + s.name.len() as f64 * 7.0;
        }
    }

    // Bars
    let group_w = plot_w / categories.len() as f64;
    let inner = group_w * 0.72;
    let bar_w = inner / series.len() as f64;

    for (ci, cat) in categories.iter().enumerate() {
        let gx = ml + ci as f64 * group_w + (group_w - inner) / 2.0;
        for (si_, s) in series.iter().enumerate() {
            let Some(&v) = s.values.get(ci) else { continue };
            let x = gx + si_ as f64 * bar_w;
            let y = scale(v);
            let h = (mt + plot_h - y).max(1.0);
            svg.push_str(&format!(
                r#"<rect x="{x:.1}" y="{y:.1}" width="{:.1}" height="{h:.1}" rx="3" fill="{}"/>
<text class="val" x="{:.1}" y="{:.1}" text-anchor="middle">{}</text>
"#,
                bar_w - 3.0,
                s.color,
                x + (bar_w - 3.0) / 2.0,
                y - 5.0,
                si(v)
            ));
        }
        svg.push_str(&format!(
            r#"<text class="axis" x="{:.1}" y="{:.1}" text-anchor="middle">{}</text>
"#,
            ml + ci as f64 * group_w + group_w / 2.0,
            mt + plot_h + 19.0,
            esc(cat)
        ));
    }

    // Axis labels
    svg.push_str(&format!(
        r#"<text class="axis" x="{:.1}" y="{:.1}" text-anchor="middle">{}</text>
<text class="axis" x="16" y="{:.1}" text-anchor="middle" transform="rotate(-90 16 {:.1})">{}</text>
</svg>
"#,
        ml + plot_w / 2.0,
        H - 14.0,
        esc(x_label),
        mt + plot_h / 2.0,
        mt + plot_h / 2.0,
        esc(y_label)
    ));
    svg
}

/// Compact axis and value labels. Keeps a decimal below 10k so that 1080 reads as
/// `1.1k` rather than collapsing to an unhelpful `1k`.
fn si(v: f64) -> String {
    let a = v.abs();
    if a >= 1e9 {
        format!("{:.1}B", v / 1e9)
    } else if a >= 1e6 {
        format!("{:.1}M", v / 1e6)
    } else if a >= 1e4 {
        format!("{:.0}k", v / 1e3)
    } else if a >= 1e3 {
        format!("{:.1}k", v / 1e3)
    } else if a >= 10.0 {
        format!("{v:.0}")
    } else if a > 0.0 {
        format!("{v:.1}")
    } else {
        "0".into()
    }
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn si_labels_stay_short() {
        assert_eq!(si(0.0), "0");
        assert_eq!(si(1_200.0), "1.2k");
        assert_eq!(si(48_000.0), "48k");
        assert_eq!(si(3_400_000.0), "3.4M");
        assert_eq!(si(42.0), "42");
    }

    #[test]
    fn median_of_an_even_count_is_deterministic() {
        assert_eq!(median(&mut [3.0, 1.0, 2.0, 4.0]), 3.0);
        assert_eq!(median(&mut [5.0]), 5.0);
    }

    #[test]
    fn charts_are_valid_standalone_svg_with_both_themes() {
        let svg = bar_chart(
            "T",
            "y",
            &["a".into(), "b".into()],
            "x",
            &[Series {
                name: "s".into(),
                color: "#4f7cff",
                values: vec![1.0, 10.0],
            }],
            false,
        );
        assert!(svg.starts_with("<svg xmlns="));
        assert!(svg.trim_end().ends_with("</svg>"));
        assert!(svg.contains("prefers-color-scheme: dark"));
        assert!(!svg.contains("<script"));
        assert_eq!(svg.matches("<rect").count(), 2);
    }

    #[test]
    fn a_log_chart_keeps_small_bars_visible() {
        let svg = bar_chart(
            "T",
            "y",
            &["big".into(), "small".into()],
            "",
            &[Series {
                name: "s".into(),
                color: "#4f7cff",
                values: vec![500_000.0, 800.0],
            }],
            true,
        );
        // Both bars must have a positive height; a linear scale would collapse the
        // smaller one to nothing at this ratio.
        let heights: Vec<f64> = svg
            .match_indices("height=\"")
            .filter_map(|(i, _)| {
                let rest = &svg[i + 8..];
                rest[..rest.find('"')?].parse::<f64>().ok()
            })
            .filter(|h| *h < 400.0)
            .collect();
        assert!(heights.iter().all(|h| *h > 5.0), "{heights:?}");
    }

    #[test]
    fn the_generated_pack_is_valid() {
        let server = MockServer::start(wide_routes(3, 500));
        let pack = pilotage::pack::Pack::parse(&wide_pack(&server, 3)).unwrap();
        assert_eq!(pack.source.len(), 3);
        assert_eq!(pack.metric.len(), 3);
        assert!(pack.validate().is_empty(), "{:?}", pack.validate());
    }
}
